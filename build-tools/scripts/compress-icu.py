"""Embed the complete ICU package as a deterministic zstd frame."""
from pathlib import Path
import zstandard

import typer


# Borrows paths through return; owns temporary bytes locally. Writes build-owned
# generated source only when contents change; failures retain no open files.
def main(source: Path, output: Path) -> None:
    original = source.read_bytes()
    params = zstandard.ZstdCompressionParameters.from_level(
        22, source_size=len(original), enable_ldm=True, write_checksum=True
    )
    compressed = zstandard.ZstdCompressor(compression_params=params).compress(original)
    if zstandard.ZstdDecompressor().decompress(compressed) != original:
        raise RuntimeError("ICU zstd round-trip mismatch")
    lines = ["// Generated by compress-icu.py; do not edit.",
             "#include <cstddef>",
             'extern "C" {',
             "extern const unsigned char v8_zig_icu_compressed[] = {"]
    for offset in range(0, len(compressed), 24):
        lines.append(",".join(str(value) for value in compressed[offset:offset + 24]) + ",")
    lines.extend(["};",
                  f"extern const size_t v8_zig_icu_compressed_size = {len(compressed)};",
                  f"extern const size_t v8_zig_icu_original_size = {len(original)};",
                  "}", ""])
    contents = "\n".join(lines)
    if not output.exists() or output.read_text() != contents:
        output.write_text(contents)
    typer.echo(f"ICU data: {len(original):,} -> {len(compressed):,} bytes "
               f"({100 * len(compressed) / len(original):.1f}%)")


if __name__ == "__main__":
    typer.run(main)
