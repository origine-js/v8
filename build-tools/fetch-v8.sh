#!/bin/sh
# Idempotently prepares depot_tools and the V8 checkout inside the cache root.
# Each stage is guarded by a `.bootstrap-complete` marker; delete it to redo the stage.
#
# usage: fetch-v8.sh <cache_root> <v8_version> <depot_tools_src>
set -eu

cache=$1
version=$2
depot_src=$3

depot="$cache/depot_tools-$version"
v8="$cache/v8-$version"

if [ ! -f "$depot/.bootstrap-complete" ]; then
    echo "Bootstrapping depot_tools into $depot"
    rm -rf "$depot"
    cp -R "$depot_src" "$depot"
    chmod -R u+w "$depot"
    printf '{"user":"","status":"opt-out","countdown":0,"version":1}\n' >"$depot/build_telemetry.cfg"
    (cd "$depot" && PATH="$depot:$PATH" ./ensure_bootstrap)
    touch "$depot/.bootstrap-complete"
fi

if [ ! -f "$v8/.bootstrap-complete" ]; then
    echo "Fetching V8 $version into $v8 (this will take a while)"
    mkdir -p "$v8/build/config"
    cat >"$v8/.gclient" <<EOF
solutions = [
  {
    "name": ".",
    "url": "https://chromium.googlesource.com/v8/v8.git@$version",
    "deps_file": "DEPS",
    "managed": False,
    "custom_deps": {},
  },
]
EOF
    echo "# Generated by Zig build system" >"$v8/build/config/gclient_args.gni"
    (cd "$v8" && PATH="$depot:$PATH" "$depot/gclient" sync)
    (cd "$v8" && PATH="$depot:$PATH" "$depot/python-bin/python3" tools/clang/scripts/update.py)
    touch "$v8/.bootstrap-complete"
fi
